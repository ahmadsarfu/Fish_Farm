-- FRESH INSTALL ONLY. Select an empty database first.
-- Existing installations must use farm-batch-upgrade.sql instead.
DELIMITER $$
DROP PROCEDURE IF EXISTS fishfarm_install_empty$$
CREATE PROCEDURE fishfarm_install_empty()
BEGIN
 IF EXISTS(SELECT 1 FROM information_schema.tables WHERE table_schema=DATABASE()) THEN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Fresh installation requires an empty database. Use farm-batch-upgrade.sql to upgrade existing data.';
 END IF;
